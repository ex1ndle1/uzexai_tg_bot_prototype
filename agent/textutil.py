"""Текстовые утилиты: нормализация и транслитерация названий.

В реестре названия компаний встречаются и кириллицей, и латиницей
(«КЕКУХО БРОКЕР» / "Tirimer Savdo"). Чтобы поиск по названию работал
независимо от алфавита, в ETL строится латинский вариант имени.
"""

from __future__ import annotations

import re

_TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "yo",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
    "ў": "o", "қ": "q", "ғ": "g", "ҳ": "h", "ҷ": "j",
}


def normalize_text(value: str) -> str:
    """Нижний регистр, пунктуация/дефисы -> пробел, схлопывание пробелов."""
    value = value.lower().replace("ё", "е")
    return " ".join(re.sub(r"[^a-zа-я0-9]+", " ", value).split())


def translit(value: str) -> str:
    """Кириллица -> латиница + нормализация; латиница остаётся как есть."""
    lowered = value.lower()
    converted = "".join(_TRANSLIT.get(ch, ch) for ch in lowered)
    return normalize_text(converted)
